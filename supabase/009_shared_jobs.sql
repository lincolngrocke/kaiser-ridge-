-- ════════════════════════════════════════════════════════════════════════════
--  009 — SHARE ONE JOB BY CODE
--
--  WHAT THIS IS FOR
--  Groovework is becoming single-user. Nobody sits "under" anybody. If you want
--  someone to have one of your jobs, you send them a COPY: the app parks the job
--  here under a short code, you pass the code on however you like, and they type
--  it into their own app to collect it. It is a copy, not a connection — nothing
--  links the two afterwards.
--
--  THE ONE RULE THAT SHAPES THE TABLE
--  ⭐ A CODE MUST NOT BE A WAY TO LOOK AROUND. The collector is a stranger to the
--  sender's org, so an ordinary SELECT policy cannot serve them: any policy loose
--  enough to let a stranger read the row they hold a code for would let them read
--  every row. So there is NO select for strangers at all. Collection goes through
--  get_shared_job(), which is SECURITY DEFINER and returns exactly one payload for
--  exactly one code. Same shape as claim_invite() in 005, for the same reason.
--
--  WHAT IS IN A PAYLOAD
--  Job name, tasks in order, batches, which tasks repeat, steps, guides and video
--  links, and the sender's learned times (which arrive as ESTIMATES on the other
--  phone, never as measurements). No timesheets, no to-dos, no location, nothing
--  about when or how often the sender worked.
--
--  SAFE TO RE-RUN.
-- ════════════════════════════════════════════════════════════════════════════

-- ── 1. Table ───────────────────────────────────────────────────────────────
create table if not exists public.shared_jobs (
  code        text primary key,
  payload     jsonb       not null,
  created_by  uuid        not null default auth.uid() references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null default (now() + interval '7 days'),
  -- A job is a few KB. This stops the table being used as free file storage.
  constraint shared_jobs_payload_size check (octet_length(payload::text) < 400000),
  -- Codes are generated by the app from an alphabet with no 0/O/1/I/L in it.
  constraint shared_jobs_code_shape   check (code ~ '^[A-HJ-KM-NP-Z2-9]{7}$')
);

create index if not exists shared_jobs_owner_idx on public.shared_jobs (created_by, created_at desc);

-- ── 2. Row level security ──────────────────────────────────────────────────
alter table public.shared_jobs enable row level security;

-- You can see and remove the codes YOU made. Nobody can see anyone else's.
drop policy if exists shared_jobs_select on public.shared_jobs;
create policy shared_jobs_select on public.shared_jobs
  for select using (created_by = auth.uid());

drop policy if exists shared_jobs_insert on public.shared_jobs;
create policy shared_jobs_insert on public.shared_jobs
  for insert with check (created_by = auth.uid());

drop policy if exists shared_jobs_delete on public.shared_jobs;
create policy shared_jobs_delete on public.shared_jobs
  for delete using (created_by = auth.uid());

-- No UPDATE policy on purpose: a shared copy is what it was when it was sent.
-- To change it, share the job again and get a new code.

-- ── 3. Collecting ──────────────────────────────────────────────────────────
-- Returns the payload for one code, or raises a message the app shows as-is.
create or replace function public.get_shared_job(_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  sj public.shared_jobs%rowtype;
begin
  if auth.uid() is null then
    raise exception 'not signed in';
  end if;

  select * into sj
    from public.shared_jobs
   where code = upper(regexp_replace(coalesce(_code, ''), '[^A-Za-z0-9]', '', 'g'));

  if not found then raise exception 'invalid share code'; end if;
  if sj.expires_at < now() then raise exception 'share code expired'; end if;

  return sj.payload;
end;
$$;

-- ── 4. Grants ──────────────────────────────────────────────────────────────
-- ⚠️ 003_lockdown.sql revokes default privileges, so a NEW TABLE IS INVISIBLE TO
--    THE DATA API until granted explicitly. Without this block the share button
--    fails with 42501 and nothing says why.
grant select, insert, delete on public.shared_jobs to authenticated;
grant execute on function public.get_shared_job(text) to authenticated;

-- anon gets nothing, ever. Sharing and collecting both need a signed-in user.
revoke all on public.shared_jobs from anon;
revoke execute on function public.get_shared_job(text) from anon;
revoke execute on function public.get_shared_job(text) from public;

-- ── Check ──────────────────────────────────────────────────────────────────
-- Run this after the block above. Expect:
--   • policies:  shared_jobs_delete, shared_jobs_insert, shared_jobs_select
--   • grants:    DELETE, INSERT, SELECT   (an EMPTY grants row means the table is
--                invisible to the app — re-run section 4)
--   • function:  get_shared_job
select 'policies' as what, string_agg(policyname, ', ' order by policyname) as found
  from pg_policies where schemaname = 'public' and tablename = 'shared_jobs'
union all
select 'grants', string_agg(privilege_type, ', ' order by privilege_type)
  from information_schema.role_table_grants
 where table_schema = 'public' and table_name = 'shared_jobs' and grantee = 'authenticated'
union all
select 'function', string_agg(proname, ', ')
  from pg_proc where proname = 'get_shared_job';
